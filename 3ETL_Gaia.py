import requests
import pandas as pd
from io import StringIO
import mysql.connector
from mysql.connector import Error
from sqlalchemy import create_engine
import sys

print("Descargando datos del archivo Gaia DR3 (ESA)...")
# Filtramos por magnitud < 10 para evitar un escaneo completo de la tabla (Timeout)
query = """
SELECT TOP 3000
    source_id, ra, dec, phot_g_mean_mag,
    parallax, pmra, pmdec, radial_velocity,
    teff_gspphot, logg_gspphot
FROM gaiadr3.gaia_source
WHERE parallax IS NOT NULL
  AND radial_velocity IS NOT NULL
  AND teff_gspphot IS NOT NULL
  AND phot_g_mean_mag < 10
"""

url = "https://gea.esac.esa.int/tap-server/tap/sync"
params = {
    "REQUEST": "doQuery",
    "LANG": "ADQL",
    "FORMAT": "csv",
    "QUERY": query
}

respuesta = requests.get(url, params=params)

# 🛑 FRENO DE EMERGENCIA: Si la API falla, mostramos el error real y detenemos el script
if respuesta.status_code != 200:
    print(f"❌ Error del servidor de Gaia (Código {respuesta.status_code}):")
    print(respuesta.text)
    sys.exit(1)

df = pd.read_csv(StringIO(respuesta.text))

print("Procesando y normalizando DataFrames...")
df = df.reset_index(drop=True)
df.insert(0, "id_estrella", range(1, len(df) + 1))

# Tabla 1: Estrella
estrellas = df[["id_estrella", "source_id", "ra", "dec", "phot_g_mean_mag"]].copy()
estrellas = estrellas.rename(columns={"phot_g_mean_mag": "magnitud_g"})

# Tabla 2: Cinemática
cinematica = df[["id_estrella", "parallax", "pmra", "pmdec", "radial_velocity"]].copy()
cinematica.insert(0, "id_cinematica", range(1, len(cinematica) + 1))
cinematica = cinematica.rename(columns={"parallax": "paralaje", "pmra": "mov_propio_ra", "pmdec": "mov_propio_dec", "radial_velocity": "vel_radial"})

# Tabla 3: Física Estelar
fisica = df[["id_estrella", "teff_gspphot", "logg_gspphot"]].copy()
fisica.insert(0, "id_fisica", range(1, len(fisica) + 1))
fisica = fisica.rename(columns={"teff_gspphot": "temperatura", "logg_gspphot": "gravedad"})

print("Creando base de datos y esquema relacional...")
config = {'host': 'mysql84', 'user': 'root', 'password': 'root'}

try:
    conexion = mysql.connector.connect(**config)
    cursor = conexion.cursor()
    cursor.execute("CREATE DATABASE IF NOT EXISTS gaia_db;")
    cursor.execute("USE gaia_db;")

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS estrella (
        id_estrella INT PRIMARY KEY,
        source_id BIGINT NOT NULL UNIQUE,
        ra DECIMAL(12,6),
        dec DECIMAL(12,6),
        magnitud_g DECIMAL(8,4)
    );""")

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS cinematica (
        id_cinematica INT PRIMARY KEY,
        id_estrella INT NOT NULL,
        paralaje DECIMAL(12,6),
        mov_propio_ra DECIMAL(12,6),
        mov_propio_dec DECIMAL(12,6),
        vel_radial DECIMAL(12,6),
        FOREIGN KEY (id_estrella) REFERENCES estrella(id_estrella)
    );""")

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS fisica_estelar (
        id_fisica INT PRIMARY KEY,
        id_estrella INT NOT NULL,
        temperatura DECIMAL(10,2),
        gravedad DECIMAL(8,4),
        FOREIGN KEY (id_estrella) REFERENCES estrella(id_estrella)
    );""")
    print("Esquema creado exitosamente.")
except Error as e:
    print(f"Error MySQL: {e}")
finally:
    if 'conexion' in locals() and conexion.is_connected():
        cursor.close()
        conexion.close()

print("Insertando datos respetando la integridad referencial...")
engine = create_engine("mysql+pymysql://root:root@mysql84:3306/gaia_db")
estrellas.to_sql(name='estrella', con=engine, if_exists='append', index=False)
cinematica.to_sql(name='cinematica', con=engine, if_exists='append', index=False)
fisica.to_sql(name='fisica_estelar', con=engine, if_exists='append', index=False)

print("¡Procesamiento finalizado! Base de datos de Gaia lista.")